export function resolveLocationCoords(location: string | null | undefined, title: string = ''): [number, number] | null {
  const text = `${location || ''} ${title || ''}`.trim()
  if (!text) return null
  
  // 精準匹配
  for (const [key, coords] of Object.entries(LOCATION_COORDS)) {
    if (text.includes(key)) {
      return coords
    }
  }
  
  // 若包含線上/遠端關鍵字則不標註
  if (text.includes('線上') || text.includes('google') || text.includes('classroom')) {
    return null
  }
  
  // 預設 fallback 到台北
  return LOCATION_COORDS['台北']
}
